export function mergeOfficial157ChartOfAccounts(existingHeads: AccountHead[] = []): {
  merged: AccountHead[];
  added: number;
  updated: number;
  totalOfficial: number;
} {
  const byCode = new Map<string, AccountHead>();
  const byId = new Map<string, AccountHead>();
  for (const h of existingHeads || []) {
    if (h?.code) byCode.set(String(h.code), h);
    if (h?.id) byId.set(String(h.id), h);
  }

  let added = 0;
  let updated = 0;

  const merged: AccountHead[] = OFFICIAL_157_CHART_OF_ACCOUNTS.map((official) => {
    const existing = byCode.get(official.code) || byId.get(official.id);
    if (existing) {
      updated++;
      return {
        ...official,
        ...existing,
        id: existing.id || official.id,
        srNo: existing.srNo ?? official.srNo,
        accountId: existing.accountId || official.accountId,
        code: official.code,
        ledgerCode: existing.ledgerCode || official.ledgerCode,
        mainCode: existing.mainCode || official.mainCode,
        mainAccount: existing.mainAccount || official.mainAccount,
        groupCode: existing.groupCode || official.groupCode,
        groupName: existing.groupName || official.groupName,
        accountType: existing.accountType || official.accountType,
        balance: existing.balance === undefined ? 0 : existing.balance,
        campusBalances: existing.campusBalances ? { ...existing.campusBalances } : {},
      };
    } else {
      added++;
      return {
        ...official,
        balance: 0,
        campusBalances: {},
      };
    }
  });

  const officialCodes = new Set(OFFICIAL_157_CHART_OF_ACCOUNTS.map((o) => o.code));
  const officialIds = new Set(OFFICIAL_157_CHART_OF_ACCOUNTS.map((o) => o.id));
  for (const h of existingHeads || []) {
    if (h && !officialCodes.has(h.code) && !officialIds.has(h.id)) {
      merged.push(h);
    }
  }

  return {
    merged,
    added,
    updated,
    totalOfficial: OFFICIAL_157_CHART_OF_ACCOUNTS.length,
  };
}

